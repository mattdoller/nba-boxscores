// Port of nba_api/stats/endpoints/shotchartdetail.py.
import { normalizeResultSets, sendApiRequest } from "../http.js";
import { ContextMeasure, LeagueID, SeasonType, seasonString } from "../parameters.js";

// Returns { Shot_Chart_Detail, LeagueAverages }. Locations (LOC_X, LOC_Y) are
// in tenths of a foot with the hoop at (0, 0). Pass teamId/playerId 0 for all.
export async function shotChartDetail({
  teamId = 0,
  playerId = 0,
  contextMeasure = ContextMeasure.default,
  lastNGames = 0,
  leagueId = LeagueID.default,
  month = 0,
  opponentTeamId = 0,
  period = 0,
  seasonType = SeasonType.default,
  aheadBehind = "",
  clutchTime = "",
  contextFilter = "",
  dateFrom = "",
  dateTo = "",
  endPeriod = "",
  endRange = "",
  gameId = "",
  gameSegment = "",
  location = "",
  outcome = "",
  playerPosition = "",
  pointDiff = "",
  position = "",
  rangeType = "",
  rookieYear = "",
  season = null,
  seasonSegment = "",
  startPeriod = "",
  startRange = "",
  vsConference = "",
  vsDivision = "",
  istRound = null,
}, options) {
  const json = await sendApiRequest("shotchartdetail", {
    TeamID: teamId,
    PlayerID: playerId,
    ContextMeasure: contextMeasure,
    LastNGames: lastNGames,
    LeagueID: leagueId,
    Month: month,
    OpponentTeamID: opponentTeamId,
    Period: period,
    SeasonType: seasonType,
    AheadBehind: aheadBehind,
    ClutchTime: clutchTime,
    ContextFilter: contextFilter,
    DateFrom: dateFrom,
    DateTo: dateTo,
    EndPeriod: endPeriod,
    EndRange: endRange,
    GameID: gameId,
    GameSegment: gameSegment,
    Location: location,
    Outcome: outcome,
    PlayerPosition: playerPosition,
    PointDiff: pointDiff,
    Position: position,
    RangeType: rangeType,
    RookieYear: rookieYear,
    Season: season == null ? "" : seasonString(season),
    SeasonSegment: seasonSegment,
    StartPeriod: startPeriod,
    StartRange: startRange,
    VsConference: vsConference,
    VsDivision: vsDivision,
    ISTRound: istRound,
  }, options);
  return normalizeResultSets(json);
}
